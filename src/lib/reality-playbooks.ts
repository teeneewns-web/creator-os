function normalize(value: string) {
  return value
    .normalize("NFKC")
    .toLocaleLowerCase("th-TH")
    .replace(/\s+/gu, " ")
    .trim();
}

function includesAny(text: string, patterns: string[]) {
  return patterns.some((pattern) => text.includes(pattern));
}

export function inferProductionConstraints(
  context: Pick<
    RealityPlaybookContext,
    | "creatorChallenge"
    | "promotionDetails"
    | "prohibitedClaims"
    | "capabilities"
  >
): ProductionConstraints {
  const text = normalize(
    [
      context.creatorChallenge,
      context.promotionDetails,
      ...context.prohibitedClaims,
    ].join(" ")
  );

  const noDialogue = includesAny(text, [
    "ไม่มีบทพูด",
    "ไม่ใช้บทพูด",
    "ไร้ภาษา",
    "ไม่มีเสียงพูด",
    "ไม่ใช้เสียงพูด",
    "ไม่พูด",
    "ไม่พากย์",
  ]);
  const noOnScreenText = includesAny(text, [
    "ไม่ใช้ข้อความบนจอ",
    "ไม่มีข้อความบนจอ",
    "ไม่ใส่ข้อความบนจอ",
    "ห้ามข้อความบนจอ",
    "ไม่ใช้ตัวหนังสือบนจอ",
  ]);
  const solo = includesAny(text, [
    "ถ่ายคนเดียว",
    "ทำคนเดียว",
    "คนเดียว",
    "ไม่มีนักแสดง",
    "ไม่มีคนช่วย",
  ]);
  const zeroBudget = includesAny(text, [
    "ไม่มีงบ",
    "งบ 0",
    "งบ0",
    "ไม่เสียค่าใช้จ่าย",
    "ฟรีทั้งหมด",
  ]);
  const minimalGear = includesAny(text, [
    "ไม่มีอุปกรณ์",
    "ใช้มือถืออย่างเดียว",
    "มือถือเครื่องเดียว",
    "ไม่มีไมค์",
    "ไม่มีไฟ",
    "ไม่มีขาตั้ง",
  ]) || zeroBudget;
  const singleLocation = includesAny(text, [
    "สถานที่เดียว",
    "ไม่ใช้หลายสถานที่",
    "ไม่ใช้สถานที่หลาย",
    "ไม่มีสถานที่",
    "สถานที่หายาก",
  ]);
  const noFace =
    context.capabilities.includes("no-face") &&
    !context.capabilities.includes("face-camera");
  const noVoice =
    noDialogue ||
    (noFace && !context.capabilities.includes("voice-over"));
  const imageOnly =
    context.capabilities.includes("image-only") &&
    !context.capabilities.includes("film-product") &&
    !context.capabilities.includes("face-camera") &&
    !context.capabilities.includes("voice-over");
  const noMedia = context.capabilities.includes("no-media");

  return {
    noDialogue,
    noOnScreenText,
    solo,
    zeroBudget,
    minimalGear,
    singleLocation,
    noFace,
    noVoice,
    imageOnly,
    noMedia,
  };
}

export function getRealityLimits(
  intensity: PlanIntensity,
  constraints?: ProductionConstraints
): RealityLimits {
  const base =
    intensity === "light"
      ? { maxMinutes: 20, maxShots: 4, maxScenes: 1, maxActors: 1 }
      : intensity === "standard"
        ? { maxMinutes: 45, maxShots: 6, maxScenes: 2, maxActors: 2 }
        : { maxMinutes: 90, maxShots: 8, maxScenes: 3, maxActors: 3 };

  return {
    ...base,
    maxShots: constraints?.minimalGear
      ? Math.min(base.maxShots, 4)
      : base.maxShots,
    maxScenes: constraints?.singleLocation
      ? 1
      : base.maxScenes,
    maxActors: constraints?.solo
      ? 1
      : base.maxActors,
  };
}

function getActionCta(
  context: RealityPlaybookContext,
  mission: DirectionMission
) {
  const subject = context.productOrService;
  const angle = mission.angle;

  switch (context.desiredAction) {
    case "follow":
      return `ถ้าชอบมุม “${angle}” กดติดตามไว้เพื่อดูผลงานหรือเนื้อหาชิ้นถัดไป`;
    case "comment":
      return `พิมพ์ความคิดเห็นของคุณต่อมุม “${angle}” ไว้ใต้โพสต์`;
    case "save":
      return `บันทึกโพสต์ “${angle}” ไว้กลับมาดูหรือทำตามภายหลัง`;
    case "share":
      return `แชร์มุม “${angle}” ให้คนที่น่าจะได้ใช้ประโยชน์จากเนื้อหานี้`;
    case "message":
      return `ส่งข้อความมาพร้อมรายละเอียดที่ต้องการเกี่ยวกับ ${subject} และระบุว่าเห็นโพสต์ “${angle}”`;
    case "click":
      return `กดดูรายละเอียดจากช่องทางที่ระบุไว้ หลังตรวจข้อมูลในมุม “${angle}” แล้ว`;
    case "order":
      return `ตรวจรายละเอียดของ ${subject} ให้ครบ แล้วสั่งผ่านช่องทางที่ระบุไว้หากมุม “${angle}” ตรงกับการใช้งานของคุณ`;
    case "book":
      return `ตรวจวัน เวลา และเงื่อนไข แล้วส่งข้อมูลเพื่อจองคิว โดยอ้างอิงมุม “${angle}”`;
  }
}

function isVideoFormat(format: ContentFormat) {
  return format === "reel" || format === "video" || format === "live";
}

function getMission(
  direction: ContentDirection,
  dayNumber: number,
  round: number,
  variationIndex: number
) {
  const missions = DIRECTION_MISSIONS[direction];
  const offset = Math.max(0, round - 1) * 2 + Math.max(0, variationIndex);
  return missions[(dayNumber - 1 + offset) % missions.length];
}

function trimShots(shots: string[], maxShots: number) {
  return shots.filter(Boolean).slice(0, Math.max(1, maxShots));
}

