function calculateEstimatedMinutes(
  intensity: PlanIntensity,
  format: ContentFormat,
  shotCount: number
) {
  const caps = intensity === "light" ? 20 : intensity === "standard" ? 45 : 90;
  const base =
    format === "text" ? 8 :
    format === "image" ? 12 :
    format === "story" ? 12 :
    format === "carousel" ? 18 :
    format === "live" ? Math.min(caps, 45) :
    14 + shotCount * (intensity === "light" ? 2 : 4);

  return Math.max(8, Math.min(caps, base));
}

